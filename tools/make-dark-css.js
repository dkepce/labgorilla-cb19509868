/* Builds dark.css: the dark-mode layer for LabGorilla.
   It reads style.css + cards.css, finds every rule that uses a fixed light colour, and writes the same rule again under
   "body.dark #app" (and "body.dark #toast") with a dark colour instead. The mapping depends on the property:
   backgrounds/fills become dark surfaces, borders/strokes become dark lines, text colours become light text.
   Print (#print, @media print) is left alone so PDFs stay light.
   Run after changing colours in style.css or cards.css:   node tools/make-dark-css.js */
