const kindOf = prop => /^(color|caret-color|-webkit-text-fill-color)$/.test(prop) ? TEXT : /border|outline|stroke|text-decoration/.test(prop) ? LINE : /background|fill|box-shadow/.test(prop) ? BG : null;

function rules(css) {   // top-level rules only; @media / @keyframes blocks are skipped
  css = css.replace(/\/\*[\s\S]*?\*\//g, ""); const out = []; let i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i); if (open < 0) break;
    const sel = css.slice(i, open).trim();
    if (sel.startsWith("@")) { let d = 1, j = open + 1; while (j < css.length && d) { if (css[j] === "{") d++; else if (css[j] === "}") d--; j++; } i = j; continue; }
    const close = css.indexOf("}", open); out.push({ sel, body: css.slice(open + 1, close) }); i = close + 1;
  }
  return out;
}
const COLOR = /#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|\bwhite\b/g;
let outCss = "/* GENERATED by tools/make-dark-css.js from style.css + cards.css. Do not edit by hand; edit the maps in the script. */\n";
for (const file of ["style.css", "cards.css"]) {
  for (const r of rules(fs.readFileSync(path.join(root, file), "utf8"))) {
    const sels = r.sel.split(",").map(s => s.trim()).filter(s => s && !/^(html|body|:root|#print)\b/.test(s) && !s.includes("#print") && !/^body\./.test(s));
    if (!sels.length) continue;
    const decls = [];
    r.body.split(";").forEach(d => {
      const k = d.indexOf(":"); if (k < 0) return; const prop = d.slice(0, k).trim().toLowerCase(), val = d.slice(k + 1).trim();
      const map = kindOf(prop); if (!map) return;
      let changed = false; const nv = val.replace(COLOR, c => { const m = map[c.toLowerCase()]; if (m) { changed = true; return m; } return c; });
      if (changed) decls.push(prop + ":" + nv);
    });
    if (!decls.length) continue;
    /* :where() adds no specificity, so each dark rule is exactly as strong as the light one it replaces and states
       like .pill.on or .btn.pri keep winning; dark.css is loaded after the other style sheets */
    const pre = sels.map(s => (s.startsWith("#toast") ? ":where(body.dark) " + s : ":where(body.dark #app) " + s)).join(",");
    outCss += pre + "{" + decls.join(";") + "}\n";
  }
}
